export type CopyKey = keyof typeof copy;
export const tr = (key: CopyKey) => copy[key];
export const stageTitle = (stage: number) =>
  tr(`stage${stage}Title` as CopyKey);
export const stageGoal = (stage: number) => tr(`stage${stage}Goal` as CopyKey);
export const fieldNote = (stage: number) => tr(`note${stage}` as CopyKey);
export const number = (value: number) =>
  value < 10 && value > -10 ? value.toFixed(1) : value.toFixed(0);
export const power = (value: number) => `${number(value)} kW`;
export const diagnosticPower = (value: number) => `${value.toFixed(2)} kW`;
export const energy = (value: number) => `${number(value)} kWh`;
export const clock = (step: number, twelve = false) => {
  const hour = (step / 4) | 0,
    minutes = (step % 4) * 15;
  if (!twelve)
    return `${String(hour).padStart(2, '0')}:${String(minutes).padStart(2, '0')}`;
  return `${hour % 12 || 12}:${String(minutes).padStart(2, '0')} ${hour < 12 ? 'am' : 'pm'}`;
};
export const voltage = (tier: 'LV' | 'MV', region: 'eu' | 'na') =>
  tier === 'LV'
    ? region === 'eu'
      ? '230 V'
      : '120/240 V'
    : region === 'eu'
      ? '11,000 V'
      : '12,470 V';
export const diagnosis = (
  kind: 'transformer' | 'line' | 'grid' | 'unconnected',
  time: string,
  flow = 0,
  cap = 0,
) =>
  kind === 'unconnected'
    ? `Needs power from ${time}. No line reaches it yet.`
    : kind === 'grid'
      ? `At ${time}, the grid connection needed ${power(flow)}. Its limit is ${power(cap)}.`
      : `At ${time}, this ${kind} carried ${power(flow)}. Its limit is ${power(cap)}.`;
